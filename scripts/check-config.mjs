import assert from 'node:assert/strict';
import { configuredUrl, configuredEmail } from '../src/data/links.ts';
import { embedUrl } from '../src/utils/media.ts';
assert.equal(configuredUrl(''), undefined);
assert.equal(configuredUrl('PERSONAL_INSTAGRAM_URL'), undefined);
assert.equal(configuredUrl('javascript:alert(1)'), undefined);
assert.equal(configuredUrl('https://user:pass@instagram.com/'), undefined);
assert.equal(configuredUrl('https://www.instagram.com/xinrann_05/'), 'https://www.instagram.com/xinrann_05/');
assert.equal(configuredEmail('PERSONAL_EMAIL_ADDRESS'), undefined);
assert.equal(configuredEmail('name@example.com?bcc=another@example.com'), undefined);
assert.equal(configuredEmail('xinranchen05@gmail.com'), 'xinranchen05@gmail.com');
assert.equal(embedUrl('soundcloud', 'https://untrusted.invalid/player/'), undefined);
assert.equal(embedUrl('youtube', 'https://www.youtube.com/watch?v=test'), undefined);
assert.equal(embedUrl('bandcamp', 'not a URL'), undefined);
assert(!embedUrl('bandcamp', 'https://bandcamp.com/EmbeddedPlayer/album=123/autoplay=false/')?.includes('?autoplay'));
assert.equal(new URL(embedUrl('soundcloud', 'https://w.soundcloud.com/player/?url=test&auto_play=true')).searchParams.get('auto_play'), 'false');
assert.equal(embedUrl('youtube', 'https://www.youtube.com/embed/test?autoplay=1'), 'https://www.youtube-nocookie.com/embed/test');
console.log('Verified configured contact links and safe, non-autoplay embeds.');
assert.equal(embedUrl('spotify', 'https://open.spotify.com/embed/track/7eo76m154ogc4hewQgyOAm?autoplay=1'), 'https://open.spotify.com/embed/track/7eo76m154ogc4hewQgyOAm');
assert.equal(embedUrl('spotify', 'https://open.spotify.com/track/7eo76m154ogc4hewQgyOAm'), undefined);
assert.equal(embedUrl('spotify', 'https://untrusted.invalid/embed/track/7eo76m154ogc4hewQgyOAm'), undefined);
